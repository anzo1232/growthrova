#!/usr/bin/env python3
"""Bound generated browser evidence; never visit customer/runtime storage."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import stat

ARTIFACT_DIRS = ("compiled-app", "workspace", "research", "creative", "calendar", "media")
BUDGET_BYTES = 512 * 1024 * 1024

def _files(run):
    for name in ARTIFACT_DIRS:
        directory = run / name
        if directory.is_symlink() or not directory.is_dir():
            continue
        for path in sorted(directory.rglob("*")):
            if path.is_symlink() or not path.resolve().is_relative_to(directory.resolve()):
                continue
            if any(parent.is_symlink() for parent in path.parents if parent != run):
                continue
            if stat.S_ISREG(path.stat().st_mode):
                yield path

def _write_manifest(path, record):
    if path.is_symlink():
        raise ValueError("Retention manifest must not be a symbolic link")
    temporary = path.with_suffix(".json.pending")
    if temporary.is_symlink():
        raise ValueError("Retention temporary file must not be a symbolic link")
    temporary.write_text(json.dumps(record, indent=2) + "\n")
    temporary.replace(path)

def maintain_evidence(root, budget_bytes=BUDGET_BYTES, keep_passed=2, keep_failed=2, dry_run=False):
    root = Path(root)
    if root.name != "acceptance-runs" or root.is_symlink() or not root.is_dir():
        raise ValueError("Expected the real acceptance-runs directory")
    if type(budget_bytes) is not int or budget_bytes < 0:
        raise ValueError("Budget must be a nonnegative integer")
    if any(type(value) is not int or value < 1 for value in (keep_passed, keep_failed)):
        raise ValueError("Keep at least one passing and failing run")
    runs = []
    for directory in sorted(root.iterdir()):
        if not re.fullmatch(r"\d{8}-\d{6}", directory.name) or directory.is_symlink() or not directory.is_dir():
            continue
        receipt = directory / "receipt.json"
        if receipt.is_symlink() or not receipt.is_file():
            continue
        try:
            data = json.loads(receipt.read_text())
            results = data["results"]
            if not isinstance(results, list) or not results or type(data["sourceUnchanged"]) is not bool:
                continue
            if not all(isinstance(row, dict) and type(row.get("passed")) is bool for row in results):
                continue
        except (ValueError, KeyError, TypeError):
            continue
        passed = data["sourceUnchanged"] and all(row["passed"] for row in results)
        files = list(_files(directory))
        runs.append((directory, passed, files))
    protected = set()
    for passed, keep in ((True, keep_passed), (False, keep_failed)):
        protected.update(directory for directory, ok, _ in [row for row in runs if row[1] == passed][-keep:])
    total = sum(path.stat().st_size for _, _, paths in runs for path in paths)
    before = total
    pruned = []
    for directory, _, paths in runs:
        if total <= budget_bytes:
            break
        if directory in protected or not paths:
            continue
        manifest = directory / "retention.json"
        if manifest.is_symlink():
            continue
        record = json.loads(manifest.read_text()) if manifest.exists() else {
            "policy": "generated-browser-evidence-v1", "removed": []
        }
        entries = [{"path": str(p.relative_to(directory)), "bytes": p.stat().st_size,
                    "sha256": hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]
        size = sum(entry["bytes"] for entry in entries)
        if not dry_run:
            # Record intended deletion before removing any generated bytes. Receipts,
            # diagnostic logs and source fingerprints are deliberately outside scope.
            record["planned"] = entries
            _write_manifest(manifest, record)
            try:
                for path, entry in zip(paths, entries):
                    path.unlink()
                    record["removed"].append(entry)
                    total -= entry["bytes"]
            finally:
                record.pop("planned", None)
                _write_manifest(manifest, record)
        else:
            total -= size
        pruned.append({"run": directory.name, "bytes": size, "files": len(entries)})
    return {"dry_run": dry_run, "budget_bytes": budget_bytes, "bytes_before": before,
            "bytes_after": total, "within_budget": total <= budget_bytes,
            "protected_runs": sorted(p.name for p in protected), "pruned": pruned}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    print(json.dumps(maintain_evidence(args.root, dry_run=args.dry_run), indent=2))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
